// The "package" says which folder/namespace this file belongs to.
package com.example.campusexplorer.ui.theme

// Import Compose's Color class so we can define colors.
import androidx.compose.ui.graphics.Color

// Colors are written as 0xAARRGGBB in hexadecimal: AA = opacity (FF = fully solid),
// then the amount of Red, Green, and Blue. The "80" colors are lighter and used in dark mode.
// A light purple (main color in dark mode).
val Purple80 = Color(0xFFD0BCFF)
// A light grayish purple (secondary color in dark mode).
val PurpleGrey80 = Color(0xFFCCC2DC)
// A light pink (accent color in dark mode).
val Pink80 = Color(0xFFEFB8C8)

// The "40" colors are darker and used in light mode.
// A deep purple (main color in light mode).
val Purple40 = Color(0xFF6650a4)
// A dark grayish purple (secondary color in light mode).
val PurpleGrey40 = Color(0xFF625b71)
// A dark pink (accent color in light mode).
val Pink40 = Color(0xFF7D5260)